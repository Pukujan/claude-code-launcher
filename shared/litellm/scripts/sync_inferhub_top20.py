#!/usr/bin/env python3
"""Generate config/inferhub_top20.yaml from IRE Top 20 CSV.

Reads D:\\claude\\inferhub\\research_model_top20_recommendations.csv (override with
--csv). Writes OpenAI-compatible InferHub deployments under model_name prefix ih/.
No secrets are written; api_key is os.environ/INFERHUB_API_KEY.
"""
from __future__ import annotations

import argparse
import csv
import datetime as dt
import sys
from pathlib import Path

DEFAULT_CSV = Path(r"D:\claude\inferhub\research_model_top20_recommendations.csv")
DEFAULT_OUT = Path(__file__).resolve().parents[1] / "config" / "inferhub_top20.yaml"
DEFAULT_API_BASE = "https://api.inferhub.dev/v1"


def primary_model_id(raw: str) -> str:
    parts = [p.strip() for p in (raw or "").split(";") if p.strip()]
    if not parts:
        raise ValueError("empty model_ids")
    return parts[0]


def yaml_escape(s: str) -> str:
    if any(c in s for c in [":", "#", "{", "}", "[", "]", ",", "&", "*", "!", "|", ">", "%", "@", "`", "'", '"']):
        return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'
    return s


def build_yaml(rows: list[dict], api_base: str, source: Path) -> str:
    now = dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    lines = [
        "# GENERATED by scripts/sync_inferhub_top20.py — do not hand-edit.",
        f"# Source: {source}",
        f"# Generated: {now}",
        "# Provider group: InferHub (OpenAI-compatible). Prefix: ih/",
        "# api_key via os.environ/INFERHUB_API_KEY (never committed).",
        "model_list:",
    ]
    for row in rows:
        rank = row.get("recommendation_rank", "?")
        family = row.get("model_family", "")
        eligible = str(row.get("recommendation_eligible", "")).lower() == "true"
        mid = primary_model_id(row.get("model_ids", ""))
        name = f"ih/{mid}"
        cost = row.get("supply_weighted_median_cost_usdc_per_1m") or ""
        note = f"IRE Top20 #{rank} {family}; eligible={eligible}"
        lines.append(f"  - model_name: {yaml_escape(name)}")
        lines.append("    litellm_params:")
        lines.append(f"      model: openai/{mid}")
        lines.append(f"      api_base: {api_base}")
        lines.append("      api_key: os.environ/INFERHUB_API_KEY")
        lines.append("    model_info:")
        lines.append(f"      description: {yaml_escape(note)}")
        if cost:
            try:
                per_token = float(cost) / 1_000_000.0
                lines.append(f"      input_cost_per_token: {per_token}")
            except ValueError:
                pass
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--csv", type=Path, default=DEFAULT_CSV)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--api-base", default=DEFAULT_API_BASE)
    args = ap.parse_args()

    if not args.csv.is_file():
        print(f"ERROR: CSV not found: {args.csv}", file=sys.stderr)
        return 1

    with args.csv.open(newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    if not rows:
        print("ERROR: CSV has no rows", file=sys.stderr)
        return 1

    text = build_yaml(rows, args.api_base.rstrip("/"), args.csv)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8")
    print(f"Wrote {len(rows)} InferHub models to {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
